"""Hardware-free autonomous mission controller for the B-team integration.

The controller deliberately consumes only the shared Vision/Motion/Arm
contracts. It is a deterministic coordinator for offline and Mock runs, not a
claim that the real robot has calibrated motion or verified manipulation.
"""
from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from math import isfinite
from typing import Protocol

from rescue_contracts import (
    ActionAck,
    ActionResult,
    ActionState,
    ArmAction,
    ArmActionRequest,
    CommandAck,
    CommandSource,
    Detection,
    DriveCommand,
    ErrorCode,
    ImageFrame,
    TargetColor,
    TargetType,
    VisionResult,
    VisionStatus,
)


class BuzzerAPI(Protocol):
    def beep(self, request_id: str, duration_ms: int) -> CommandAck:
        ...


class MissionState(str, Enum):
    LINE_TRACKING = "LINE_TRACKING"
    SEARCH_LINE = "SEARCH_LINE"
    BYPASS_SIGN = "BYPASS_SIGN"
    KNOCK_SIGN = "KNOCK_SIGN"
    FIND_BALL = "FIND_BALL"
    PICK_BALL = "PICK_BALL"
    PLACE_CUP = "PLACE_CUP"
    RETURN_HOME = "RETURN_HOME"
    COMPLETE = "COMPLETE"
    SAFE_HOLD = "SAFE_HOLD"
    FAILED = "FAILED"


@dataclass(frozen=True)
class FSMEvent:
    state_before: MissionState
    state_after: MissionState
    message: str = ""
    motion_ack: CommandAck | None = None
    buzzer_ack: CommandAck | None = None
    arm_ack: ActionAck | None = None
    arm_result: ActionResult | None = None


@dataclass(frozen=True)
class FSMConfig:
    """Validated coordinator parameters kept separate from mission logic."""

    sign_trigger_distance_mm: float = 250.0
    line_lost_limit: int = 3
    bypass_ticks: int = 2
    return_ticks: int = 3
    command_ttl_ms: int = 400
    alarm_duration_ms: int = 400
    arm_action_timeout_ms: int = 3000
    line_error_scale_px: float = 160.0
    line_deadband_norm: float = 0.08
    track_speed_norm: float = 0.35
    bypass_speed_norm: float = 0.35
    search_yaw_norm: float = 0.25
    ball_speed_norm: float = 0.18
    return_speed_norm: float = -0.25

    def __post_init__(self) -> None:
        if (not isinstance(self.sign_trigger_distance_mm, (int, float))
                or isinstance(self.sign_trigger_distance_mm, bool)
                or not isfinite(self.sign_trigger_distance_mm)
                or self.sign_trigger_distance_mm <= 0):
            raise ValueError('sign_trigger_distance_mm must be a finite positive number')
        for name in ('line_lost_limit', 'bypass_ticks', 'return_ticks',
                     'command_ttl_ms', 'alarm_duration_ms', 'arm_action_timeout_ms'):
            value = getattr(self, name)
            if not isinstance(value, int) or isinstance(value, bool) or value <= 0:
                raise ValueError(f'{name} must be a positive integer')
        if not 100 <= self.command_ttl_ms <= 2000:
            raise ValueError('command_ttl_ms must be between 100 and 2000')
        if not 1 <= self.alarm_duration_ms <= 2000:
            raise ValueError('alarm_duration_ms must be between 1 and 2000')
        if not 100 <= self.arm_action_timeout_ms <= 30000:
            raise ValueError('arm_action_timeout_ms must be between 100 and 30000')
        if (not isinstance(self.line_error_scale_px, (int, float))
                or isinstance(self.line_error_scale_px, bool)
                or not isfinite(self.line_error_scale_px)
                or self.line_error_scale_px <= 0):
            raise ValueError('line_error_scale_px must be a finite positive number')
        for name in ('track_speed_norm', 'bypass_speed_norm', 'search_yaw_norm',
                     'ball_speed_norm', 'return_speed_norm', 'line_deadband_norm'):
            value = getattr(self, name)
            if (not isinstance(value, (int, float)) or isinstance(value, bool)
                    or not isfinite(value) or not -1.0 <= value <= 1.0):
                raise ValueError(f'{name} must be a finite normalized value')
        if self.line_deadband_norm <= 0:
            raise ValueError('line_deadband_norm must be greater than zero')


class AutonomousFSM:
    """Small, deterministic mission FSM suitable for contract-level testing.

    Call :meth:`process_frame` at the coordinator cadence. The visual input is
    always a fresh ``VisionResult`` from ``VisionAPI``; no detector internals
    are accessed. All command IDs are generated by this coordinator and every
    accepted action remains ``DONE_UNVERIFIED`` until an external verifier
    supplies evidence, in line with the v0.2.1 contract.
    """

    _INTERESTS = frozenset({TargetType.LINE, TargetType.SIGN, TargetType.BALL,
                             TargetType.CUP, TargetType.STORAGE_AREA})

    def __init__(self, vision, motion, arm, buzzer: BuzzerAPI, clock,
                 *, config: FSMConfig | None = None,
                 sign_trigger_distance_mm: float | None = None,
                 line_lost_limit: int | None = None,
                 bypass_ticks: int | None = None,
                 return_ticks: int | None = None) -> None:
        self.vision = vision
        self.motion = motion
        self.arm = arm
        self.buzzer = buzzer
        self.clock = clock
        overrides = (sign_trigger_distance_mm, line_lost_limit, bypass_ticks, return_ticks)
        if config is not None and not isinstance(config, FSMConfig):
            raise TypeError('config must be an FSMConfig')
        if config is not None and any(value is not None for value in overrides):
            raise ValueError('use config or legacy parameter overrides, not both')
        if config is None:
            config = FSMConfig(
                sign_trigger_distance_mm=(250.0 if sign_trigger_distance_mm is None
                                           else sign_trigger_distance_mm),
                line_lost_limit=3 if line_lost_limit is None else line_lost_limit,
                bypass_ticks=2 if bypass_ticks is None else bypass_ticks,
                return_ticks=3 if return_ticks is None else return_ticks,
            )
        self.config = config
        self.state = MissionState.LINE_TRACKING
        self._sequence = 0
        self._line_lost = 0
        self._phase_ticks = 0
        self._pending_action_id: str | None = None
        self._selected_cup: int = 2

    def process_frame(self, frame: ImageFrame, *, home_reached: bool = False) -> FSMEvent:
        result = self.vision.observe(frame, self._INTERESTS)
        return self.step(result, home_reached=home_reached)

    def step(self, vision: VisionResult, *, home_reached: bool = False) -> FSMEvent:
        before = self.state
        if self.state in (MissionState.COMPLETE, MissionState.FAILED):
            return FSMEvent(state_before=before, state_after=self.state,
                            message='mission already terminal')
        if vision.status != VisionStatus.OK:
            stop = self._stop('stale-or-invalid-vision')
            self.state = (MissionState.SAFE_HOLD if vision.status == VisionStatus.STALE_FRAME
                          else MissionState.FAILED)
            return FSMEvent(state_before=before, state_after=self.state,
                            message=f'vision status {vision.status.value}; motion held safely',
                            motion_ack=stop)
        self._update_cup_selection(vision)

        if self.state == MissionState.LINE_TRACKING:
            return self._line_tracking(vision, before)
        if self.state == MissionState.SEARCH_LINE:
            return self._search_line(vision, before)
        if self.state == MissionState.BYPASS_SIGN:
            return self._bypass(before)
        if self.state == MissionState.KNOCK_SIGN:
            return self._poll_or_start_arm(ArmAction.HIT_SIGN, MissionState.LINE_TRACKING,
                                            before)
        if self.state == MissionState.FIND_BALL:
            return self._find_ball(vision, before)
        if self.state == MissionState.PICK_BALL:
            return self._poll_or_start_arm(ArmAction.PICK_BALL, MissionState.PLACE_CUP,
                                            before)
        if self.state == MissionState.PLACE_CUP:
            action = (ArmAction.PLACE_CUP_3X if self._selected_cup == 3
                      else ArmAction.PLACE_CUP_2X)
            return self._poll_or_start_arm(action, MissionState.RETURN_HOME, before)
        if self.state == MissionState.RETURN_HOME:
            return self._return_home(vision, before, home_reached)
        self.state = MissionState.FAILED
        return FSMEvent(state_before=before, state_after=self.state,
                        message='FSM reached an unsupported state')

    def _line_tracking(self, vision: VisionResult, before: MissionState) -> FSMEvent:
        sign = self._confirmed(vision, TargetType.SIGN)
        if sign is not None and self._sign_is_close(sign):
            stop = self._stop('sign-approach')
            buzzer = self.buzzer.beep(self._id('beep'), self.config.alarm_duration_ms)
            if stop.accepted and buzzer.accepted:
                if sign.color == TargetColor.YELLOW:
                    self.state = MissionState.BYPASS_SIGN
                    self._phase_ticks = 0
                elif sign.color == TargetColor.BLACK:
                    self.state = MissionState.KNOCK_SIGN
                    self._pending_action_id = None
                else:
                    self.state = MissionState.FAILED
                    return FSMEvent(state_before=before, state_after=self.state,
                                    message='unrecognized sign color; mission failed',
                                    motion_ack=stop, buzzer_ack=buzzer)
                return FSMEvent(state_before=before, state_after=self.state,
                                message='sign alarm dispatched', motion_ack=stop,
                                buzzer_ack=buzzer)
            self.state = MissionState.SAFE_HOLD
            return FSMEvent(state_before=before, state_after=self.state,
                            message='could not establish sign safety stop',
                            motion_ack=stop, buzzer_ack=buzzer)

        # A ball can be reported together with a valid line. Hand it to the
        # dedicated acquisition state so the same scripted frame works in a
        # Mock run and the coordinator never drives while starting the arm.
        if self._confirmed(vision, TargetType.BALL) is not None:
            self.state = MissionState.FIND_BALL
            return self._find_ball(vision, before)

        if vision.line is None or not vision.line.found:
            self._line_lost += 1
            if self._line_lost >= self.config.line_lost_limit:
                stop = self._stop('line-lost-limit')
                self.state = MissionState.SAFE_HOLD
                return FSMEvent(state_before=before, state_after=self.state,
                                message='line lost; finite search exhausted',
                                motion_ack=stop)
            self.state = MissionState.SEARCH_LINE
            return self._search_line(vision, before, count_miss=False)

        self._line_lost = 0
        line_error_px = 0.0 if vision.line.error_px is None else vision.line.error_px
        yaw = max(-1.0, min(1.0, line_error_px / self.config.line_error_scale_px))
        # The default MockMotion rejects combined axes. Prefer forward motion
        # when centered and a bounded yaw search while correcting laterally.
        combined = bool(getattr(self.motion, 'supports_combined', False))
        if combined:
            x, command_yaw = self.config.track_speed_norm, -yaw
        elif abs(yaw) > self.config.line_deadband_norm:
            x, command_yaw = 0.0, -yaw
        else:
            x, command_yaw = self.config.track_speed_norm, 0.0
        ack = self._drive(x, 0.0, command_yaw)
        if not ack.accepted:
            self.state = MissionState.SAFE_HOLD
            return FSMEvent(state_before=before, state_after=self.state,
                            message='line command rejected', motion_ack=ack)
        return FSMEvent(state_before=before, state_after=self.state,
                        message='tracking line', motion_ack=ack)

    def _search_line(self, vision: VisionResult, before: MissionState,
                     *, count_miss: bool = True) -> FSMEvent:
        if vision.line is not None and vision.line.found:
            self._line_lost = 0
            self.state = MissionState.LINE_TRACKING
            return self._line_tracking(vision, before)
        if count_miss:
            self._line_lost += 1
        if self._line_lost >= self.config.line_lost_limit:
            ack = self._stop('line-lost-limit')
            self.state = MissionState.SAFE_HOLD
            return FSMEvent(state_before=before, state_after=self.state,
                            message='line lost; finite search exhausted',
                            motion_ack=ack)
        ack = self._drive(0.0, 0.0,
                          self.config.search_yaw_norm if self._line_lost % 2
                          else -self.config.search_yaw_norm)
        if not ack.accepted:
            self.state = MissionState.SAFE_HOLD
        return FSMEvent(state_before=before, state_after=self.state,
                        message='finite line search', motion_ack=ack)

    def _bypass(self, before: MissionState) -> FSMEvent:
        self._phase_ticks += 1
        ack = self._drive(0.0, self.config.bypass_speed_norm, 0.0)
        if not ack.accepted:
            self.state = MissionState.SAFE_HOLD
            return FSMEvent(state_before=before, state_after=self.state,
                            message='yellow-sign bypass rejected', motion_ack=ack)
        if self._phase_ticks >= self.config.bypass_ticks:
            self._phase_ticks = 0
            self.state = MissionState.LINE_TRACKING
        return FSMEvent(state_before=before, state_after=self.state,
                        message='yellow-sign bypass', motion_ack=ack)

    def _find_ball(self, vision: VisionResult, before: MissionState) -> FSMEvent:
        ball = self._confirmed(vision, TargetType.BALL)
        if ball is not None:
            stop = self._stop('ball-approach')
            if stop.accepted:
                self.state = MissionState.PICK_BALL
                self._pending_action_id = None
            else:
                self.state = MissionState.SAFE_HOLD
            return FSMEvent(state_before=before, state_after=self.state,
                            message='ball target acquired', motion_ack=stop)
        ack = self._drive(self.config.ball_speed_norm, 0.0, 0.0)
        if not ack.accepted:
            self.state = MissionState.SAFE_HOLD
        return FSMEvent(state_before=before, state_after=self.state,
                        message='searching for ball', motion_ack=ack)

    def _return_home(self, vision: VisionResult, before: MissionState,
                     home_reached: bool) -> FSMEvent:
        area = self._confirmed(vision, TargetType.STORAGE_AREA)
        self._phase_ticks += 1
        if (home_reached or area is not None
                or self._phase_ticks >= self.config.return_ticks):
            stop = self._stop('return-home')
            self.state = MissionState.COMPLETE if stop.accepted else MissionState.SAFE_HOLD
            self._phase_ticks = 0
            return FSMEvent(state_before=before, state_after=self.state,
                            message='returned to start area', motion_ack=stop)
        ack = self._drive(self.config.return_speed_norm, 0.0, 0.0)
        if not ack.accepted:
            self.state = MissionState.SAFE_HOLD
        return FSMEvent(state_before=before, state_after=self.state,
                        message='returning home', motion_ack=ack)

    def _poll_or_start_arm(self, action: ArmAction, next_state: MissionState,
                           before: MissionState) -> FSMEvent:
        if self._pending_action_id is None:
            request = ArmActionRequest(self._id('arm'), self.clock.now_ms, action,
                                       None, self.config.arm_action_timeout_ms,
                                       CommandSource.AUTO)
            ack = self.arm.start_action(request)
            if not ack.accepted:
                self.state = MissionState.SAFE_HOLD if ack.error_code in {
                    ErrorCode.BUSY, ErrorCode.SAFETY_STOP, ErrorCode.MODE_DENIED,
                } else MissionState.FAILED
                return FSMEvent(state_before=before, state_after=self.state,
                                message='arm action rejected', arm_ack=ack)
            if (not isinstance(ack.action_id, str)
                    or not ack.action_id.strip()):
                self.state = MissionState.SAFE_HOLD
                return FSMEvent(state_before=before, state_after=self.state,
                                message='arm accepted without action_id; held safely',
                                arm_ack=ack)
            self._pending_action_id = ack.action_id
            return FSMEvent(state_before=before, state_after=self.state,
                            message=f'{action.value} accepted', arm_ack=ack)

        result = self.arm.get_status(self._pending_action_id)
        if result.state in (ActionState.ACCEPTED, ActionState.RUNNING):
            return FSMEvent(state_before=before, state_after=self.state,
                            message=f'{action.value} running', arm_result=result)
        self._pending_action_id = None
        if result.state == ActionState.DONE_UNVERIFIED:
            self.state = next_state
            return FSMEvent(state_before=before, state_after=self.state,
                            message=f'{action.value} done; physical result remains unverified',
                            arm_result=result)
        self.state = MissionState.SAFE_HOLD
        return FSMEvent(state_before=before, state_after=self.state,
                        message=f'{action.value} failed safely', arm_result=result)

    def _confirmed(self, vision: VisionResult, kind: TargetType) -> Detection | None:
        for item in vision.objects:
            if item.kind == kind and item.confirmed:
                return item
        return None

    def _update_cup_selection(self, vision: VisionResult) -> None:
        cup = self._confirmed(vision, TargetType.CUP)
        if cup is not None and cup.cup_multiplier in (2, 3):
            self._selected_cup = cup.cup_multiplier

    def _sign_is_close(self, sign: Detection) -> bool:
        return (sign.distance_mm is not None
                and sign.distance_mm >= 0
                and sign.distance_mm <= self.config.sign_trigger_distance_mm)

    def _id(self, prefix: str) -> str:
        self._sequence += 1
        return f'{prefix}-{self._sequence:05d}'

    def _drive(self, x: float, y: float, yaw: float) -> CommandAck:
        return self.motion.drive(DriveCommand(self._id('drive'), self.clock.now_ms,
                                              x, y, yaw, self.config.command_ttl_ms,
                                              CommandSource.AUTO))

    def _stop(self, prefix: str) -> CommandAck:
        return self.motion.stop(self._id(prefix))
